var url = "";

$(document).ready(function () {
    $('.select2').select2();
    var context = window.location.pathname.substring(1);
    url = context.split('/')[0];

    var date = new Date();
    var today = new Date(date.getFullYear(), date.getMonth(), date.getDate());
    var end = new Date(date.getFullYear(), date.getMonth(), date.getDate());
    $('#txtDateFrom').datepicker({
        todayHighlight: true,
        format: 'mm/dd/yyyy',
        endDate: '+0d',
        autoclose: true
    });
    $('#txtDateFrom').datepicker('setDate', today);

    $('#txtDateTo').datepicker({
        todayHighlight: true,
        format: 'mm/dd/yyyy',
        endDate: '+0d',
        autoclose: true
    });
    $('#txtDateTo').datepicker('setDate', today);

    $("#tblPendingUpload").DataTable({
        "scrollX": true
        , "searching": false
        , dom: 'rtip'
    });

    load_data_Pendingupload();

    $("#tblPendingUpload").DataTable().clear().draw();
});


function EnterKeySearch(event) {
    var x = event.keyCode;
    if (x == 13) {  // 27 is the ESC key
        load_data_Pendingupload();
        return false;
    }
}

function load_data_Pendingupload() {
    var search = $('#txtSearch').val().trim();
    var datefrom = $('#txtDateFrom').val();
    var dateto = $('#txtDateTo').val();
    $.ajax({
        type: 'POST',
        url: url + "/StockDisposalHistory.aspx/GetDisposalHistory",
        data: "{ search: '" + search + "', datefrom : '" + datefrom + "', dateto: '" + dateto + "' }",
        contentType: "application/json; charset=utf-8",
        dataType: "json",
        success: function (data) {
            $('#pendinguploadlist').hide();
            $('#pendinguploadlist').innerHTML = "";
            $('#pendinguploadlist').fadeIn(200);

            myJsonData = data;
            populateDataTablePendingUpload(myJsonData);

            console.log(data);
            console.log('Success');

        },
        error: function (e) {
            alert(e);
            console.log("There was an error with your request...");
            console.log("error: " + JSON.stringify(e));
        }
    });
}

